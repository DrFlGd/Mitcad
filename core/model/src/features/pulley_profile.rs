//! The grooves of timing belt pulleys (mitcad#562): the outline a Pulley
//! feature sweeps, worked out here without a geometry kernel.
//!
//! A pulley of z teeth for a belt of pitch p has the pitch diameter
//! z p / pi: the belt's pitch line (its tension members) wraps that
//! circle. The pulley's outside diameter is smaller by twice the belt's
//! pitch line offset (PLD): OD = z p / pi - 2 PLD. Its grooves are cut from
//! the outside circle, one between each pair of teeth.
//!
//! The grooves are our own construction around the published belt and
//! pulley dimensions; no geometry is taken from suppliers' model files.
//! One fixed groove serves every tooth count of a profile (a pulley's
//! groove is not generated by the belt's motion here). Sources:
//!
//! - **GT2 2 mm and GT2 3 mm** (the belt maker's published GT2 belt
//!   dimensions: pitch 2 mm, PLD 0.254 mm, tooth height 0.75 mm; pitch
//!   3 mm, PLD 0.381 mm, tooth height 1.14 mm): a round-bottomed groove
//!   0.764 mm (1.169 mm) deep and 1.494 mm (2.31 mm) wide at the outside
//!   circle, its bottom radius 0.555 mm (0.85 mm), tip radius 0.15 mm
//!   (0.25 mm).
//! - **HTD 3M and HTD 5M** (the curvilinear profile of ISO 13050: pitch
//!   3 mm, PLD 0.381 mm, tooth height 1.17 mm; pitch 5 mm, PLD 0.5715 mm,
//!   tooth height 2.06 mm): a round-bottomed groove 1.289 mm (2.199 mm)
//!   deep and 2.27 mm (3.781 mm) wide, bottom radius 0.86 mm (1.49 mm),
//!   tip radius 0.3 mm (0.43 mm).
//! - **T5** (DIN 7721, now ISO 17396: pitch 5 mm; the belt tooth 2.65 mm
//!   wide at its base, 1.2 mm high, 40 degree flanks; 0.85 mm between the
//!   pitch and outside diameters, PLD 0.425 mm, as in published pulley
//!   tables): a straight-sided groove 1.75 mm wide at its bottom, 1.25 mm
//!   deep, 50 degrees between its flanks, bottom radius 0.4 mm, tip radius
//!   0.6 mm.
//! - **XL** (ISO 5294's straight-sided groove for XL, pitch 5.08 mm,
//!   PLD 0.254 mm): 1.32 mm wide at its bottom, 1.65 mm deep, 50 degrees
//!   between its flanks, bottom radius 0.41 mm, tip radius 0.64 mm.
//!
//! A groove lies along its axis (a radius of the pulley): from its middle
//! out, a flat bottom (straight-sided grooves) or a bottom arc centred on
//! the axis (round grooves), the bottom fillet, a straight flank at the
//! groove's flank angle to the axis, tangent to the bottom, and the tip
//! fillet tangent to the flank and the outside circle.
//!
//! Outlines are closed loops of named segments in the pulley's own plane
//! coordinates: its centre at the origin, tooth 1 centred at `phase` from
//! the x axis, the teeth counter-clockwise. Segment names are the faces'
//! roles: tooth k has `tip(k)` (the land on the outside circle),
//! `tip_fillet_a(k)`, `flank_a(k)` and `root_fillet_a(k)` on its clockwise
//! side, `tip_fillet_b(k)`, `flank_b(k)` and `root_fillet_b(k)` on the
//! other, and `root(k)` is the bottom of the groove after it.

use std::f64::consts::{FRAC_PI_2, PI, TAU};

use serde::{Deserialize, Serialize};

use super::gear_profile::{NamedSegment, placed};
use crate::profile::SegmentGeometry;

/// A belt profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BeltProfile {
    #[serde(rename = "gt2_2mm")]
    Gt2Pitch2,
    #[serde(rename = "gt2_3mm")]
    Gt2Pitch3,
    #[serde(rename = "htd_3m")]
    Htd3m,
    #[serde(rename = "htd_5m")]
    Htd5m,
    #[serde(rename = "t5")]
    T5,
    #[serde(rename = "xl")]
    Xl,
}

/// Every profile, in the order the panels list them.
pub const PROFILES: [BeltProfile; 6] = [
    BeltProfile::Gt2Pitch2,
    BeltProfile::Gt2Pitch3,
    BeltProfile::Htd3m,
    BeltProfile::Htd5m,
    BeltProfile::T5,
    BeltProfile::Xl,
];

/// A groove's shape.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Groove {
    /// From the outside circle to the groove's bottom (mm).
    pub depth: f64,
    /// Half the width of the flat bottom between the bottom fillets; 0 for
    /// a round bottom (one arc centred on the groove's axis).
    pub flat: f64,
    pub bottom_radius: f64,
    /// The angle of a flank to the groove's axis (radians).
    pub flank_angle: f64,
    pub tip_radius: f64,
}

impl Groove {
    /// A round-bottomed groove `depth` deep and `width` wide where its
    /// flanks, straight on, would meet the outside circle (measured across
    /// the groove), with its bottom arc of `bottom_radius` and its tips
    /// rounded by `tip_radius`. The flanks are tangent to the bottom arc
    /// and pass through the sharp corners.
    fn round(depth: f64, width: f64, bottom_radius: f64, tip_radius: f64) -> Self {
        // Along the groove (u from its bottom) and across it (v): the
        // bottom arc's centre (r, 0), the sharp corner (h, w / 2); the flank
        // through the corner at angle phi to the axis, r from the centre:
        // (w / 2) cos phi - (h - r) sin phi = r.
        let (h, half, r) = (depth, width / 2.0, bottom_radius);
        let d = (h - r).hypot(half);
        let flank_angle = (r / d).acos() - (h - r).atan2(half);
        Self {
            depth,
            flat: 0.0,
            bottom_radius,
            flank_angle,
            tip_radius,
        }
    }

    /// A straight-sided groove: `bottom_width` across its sharp bottom
    /// corners, `depth` deep, `included` radians between its flanks, the
    /// bottom corners rounded by `bottom_radius`, the tips by
    /// `tip_radius`.
    fn straight(
        depth: f64,
        bottom_width: f64,
        included: f64,
        bottom_radius: f64,
        tip_radius: f64,
    ) -> Self {
        let phi = included / 2.0;
        let r = bottom_radius;
        // The bottom fillet's centre: r above the bottom and r inside the
        // flank, which leaves the sharp corner at t along the flank.
        let t = r * (1.0 - phi.sin()) / phi.cos();
        let flat = bottom_width / 2.0 + t * phi.sin() - r * phi.cos();
        Self {
            depth,
            flat,
            bottom_radius,
            flank_angle: phi,
            tip_radius,
        }
    }
}

/// A profile's dimensions.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ProfileData {
    /// As messages name it: `GT2 2 mm`.
    pub name: &'static str,
    /// The belt's pitch (mm).
    pub pitch: f64,
    /// The pitch line offset (PLD): half the difference between the pitch
    /// and outside diameters (mm).
    pub pitch_line_offset: f64,
    /// The fewest teeth a pulley of the profile may have.
    pub min_teeth: f64,
    pub groove: Groove,
}

impl BeltProfile {
    /// The name the definitions use: `gt2_2mm`.
    pub fn id(self) -> &'static str {
        match self {
            Self::Gt2Pitch2 => "gt2_2mm",
            Self::Gt2Pitch3 => "gt2_3mm",
            Self::Htd3m => "htd_3m",
            Self::Htd5m => "htd_5m",
            Self::T5 => "t5",
            Self::Xl => "xl",
        }
    }

    pub fn data(self) -> ProfileData {
        let degrees = |d: f64| d.to_radians();
        match self {
            Self::Gt2Pitch2 => ProfileData {
                name: "GT2 2 mm",
                pitch: 2.0,
                pitch_line_offset: 0.254,
                min_teeth: 10.0,
                groove: Groove::round(0.764, 1.494, 0.555, 0.15),
            },
            Self::Gt2Pitch3 => ProfileData {
                name: "GT2 3 mm",
                pitch: 3.0,
                pitch_line_offset: 0.381,
                min_teeth: 10.0,
                groove: Groove::round(1.169, 2.31, 0.85, 0.25),
            },
            Self::Htd3m => ProfileData {
                name: "HTD 3M",
                pitch: 3.0,
                pitch_line_offset: 0.381,
                min_teeth: 10.0,
                groove: Groove::round(1.289, 2.27, 0.86, 0.3),
            },
            Self::Htd5m => ProfileData {
                name: "HTD 5M",
                pitch: 5.0,
                pitch_line_offset: 0.5715,
                min_teeth: 12.0,
                groove: Groove::round(2.199, 3.781, 1.49, 0.43),
            },
            Self::T5 => ProfileData {
                name: "T5",
                pitch: 5.0,
                pitch_line_offset: 0.425,
                min_teeth: 10.0,
                groove: Groove::straight(1.25, 1.75, degrees(50.0), 0.4, 0.6),
            },
            Self::Xl => ProfileData {
                name: "XL",
                pitch: 5.08,
                pitch_line_offset: 0.254,
                min_teeth: 10.0,
                groove: Groove::straight(1.65, 1.32, degrees(50.0), 0.41, 0.64),
            },
        }
    }
}

/// The pitch diameter of `teeth` teeth: z p / pi.
pub fn pitch_diameter(profile: BeltProfile, teeth: f64) -> f64 {
    teeth * profile.data().pitch / PI
}

/// The outside diameter: the pitch diameter, corrected by `correction`,
/// less twice the pitch line offset.
pub fn outside_diameter(profile: BeltProfile, teeth: f64, correction: f64) -> f64 {
    pitch_diameter(profile, teeth) + correction - 2.0 * profile.data().pitch_line_offset
}

/// Half a groove in groove coordinates: the groove along +x, this half on
/// the -y side (seen along the axis, the clockwise side of the groove),
/// from its bottom out to the outside circle.
#[derive(Debug, Clone)]
pub struct HalfGroove {
    /// The whole bottom: the flat between the bottom fillets (a line), or
    /// the round bottom (an arc across the axis, both halves).
    pub bottom: SegmentGeometry,
    /// The bottom fillet of a flat bottom.
    pub bottom_fillet: Option<SegmentGeometry>,
    /// The straight flank (none where the fillets meet).
    pub flank: Option<SegmentGeometry>,
    pub tip_fillet: SegmentGeometry,
    /// The angle of the tip fillet's end on the outside circle (negative:
    /// on the -y side).
    pub tip_angle: f64,
}

/// The half groove of a profile on a pulley of `outside_radius`.
pub fn half_groove(profile: BeltProfile, outside_radius: f64) -> Result<HalfGroove, String> {
    let data = profile.data();
    let g = data.groove;
    let ro = outside_radius;
    let xb = ro - g.depth;
    if xb.is_nan() || xb <= 0.0 {
        return Err(format!(
            "a {} pulley's grooves reach its axis: its outside diameter must be more than {:.4} mm",
            data.name,
            2.0 * g.depth
        ));
    }
    let (phi, rb, rt, w) = (g.flank_angle, g.bottom_radius, g.tip_radius, g.flat);
    if !(phi > 0.0 && phi < FRAC_PI_2) || w < 0.0 {
        return Err(format!("the {} groove has no valid shape", data.name));
    }
    let beta = FRAC_PI_2 - phi;
    // The bottom fillet's centre and its end on the flank.
    let center = [xb + rb, -w];
    let p1 = [xb + rb - rb * phi.sin(), -w - rb * phi.cos()];
    // The flank's direction outwards and its normal into the material.
    let d = [phi.cos(), -phi.sin()];
    let n = [-phi.sin(), -phi.cos()];
    // The tip fillet's centre lies rt from the flank, rt inside the
    // outside circle: |p1 + rt n + s d| = ro - rt.
    let q = [p1[0] + rt * n[0], p1[1] + rt * n[1]];
    let qd = q[0] * d[0] + q[1] * d[1];
    let qq = q[0] * q[0] + q[1] * q[1];
    let reach = ro - rt;
    let disc = qd * qd - qq + reach * reach;
    if disc < 0.0 {
        return Err(format!(
            "the {} groove does not fit a pulley of {:.4} mm",
            data.name,
            2.0 * ro
        ));
    }
    let s = -qd + disc.sqrt();
    if s < -1.0e-9 {
        return Err(format!(
            "the {} groove's fillets do not fit a pulley of {:.4} mm",
            data.name,
            2.0 * ro
        ));
    }
    let s = s.max(0.0);
    let t1 = [p1[0] + s * d[0], p1[1] + s * d[1]];
    let ct = [t1[0] + rt * n[0], t1[1] + rt * n[1]];
    let tip_angle = ct[1].atan2(ct[0]);
    let tip_fillet = SegmentGeometry::Arc {
        center: ct,
        radius: rt,
        start_angle: tip_angle,
        end_angle: beta,
    };
    let flank = (s > 1.0e-9).then_some(SegmentGeometry::Line { start: p1, end: t1 });
    let (bottom, bottom_fillet) = if w > 0.0 {
        (
            SegmentGeometry::Line {
                start: [xb, -w],
                end: [xb, w],
            },
            Some(SegmentGeometry::Arc {
                center,
                radius: rb,
                start_angle: PI,
                end_angle: PI + beta,
            }),
        )
    } else {
        (
            SegmentGeometry::Arc {
                center,
                radius: rb,
                start_angle: PI - beta,
                end_angle: PI + beta,
            },
            None,
        )
    };
    Ok(HalfGroove {
        bottom,
        bottom_fillet,
        flank,
        tip_fillet,
        tip_angle,
    })
}

fn named(role: &str, index: usize, geometry: SegmentGeometry) -> NamedSegment {
    NamedSegment {
        name: format!("{role}({index})"),
        geometry,
    }
}

/// The angle a tooth's tip (its land on the outside circle) spans: the
/// pitch angle less the grooves' share; not positive when the grooves
/// overlap.
pub fn land_angle(half: &HalfGroove, teeth: f64) -> f64 {
    TAU / teeth.round() + 2.0 * half.tip_angle
}

/// Checks that `teeth` grooves of the profile fit a pulley of
/// `outside_radius`.
pub fn check_teeth(profile: BeltProfile, teeth: f64, outside_radius: f64) -> Result<(), String> {
    let half = half_groove(profile, outside_radius)?;
    if land_angle(&half, teeth) <= 1.0e-6 {
        return Err(format!(
            "{} teeth leave no land between the {} grooves",
            teeth.round(),
            profile.data().name
        ));
    }
    Ok(())
}

/// The closed outline of a toothed pulley of `outside_radius`, tooth 1
/// centred at `phase`.
pub fn toothed_outline(
    profile: BeltProfile,
    teeth: f64,
    outside_radius: f64,
    phase: f64,
) -> Result<Vec<NamedSegment>, String> {
    check_teeth(profile, teeth, outside_radius)?;
    let half = half_groove(profile, outside_radius)?;
    let z = teeth.round() as usize;
    let step = TAU / z as f64;
    let mut segments = Vec::with_capacity(8 * z);
    for i in 0..z {
        let k = i + 1;
        let c = phase + step * i as f64;
        // The groove before the tooth (its +y half, mirrored) and after it.
        let (before, after) = (c - step / 2.0, c + step / 2.0);
        if let Some(fillet) = &half.bottom_fillet {
            segments.push(named("root_fillet_a", k, placed(fillet, before, true)));
        }
        if let Some(flank) = &half.flank {
            segments.push(named("flank_a", k, placed(flank, before, true)));
        }
        segments.push(named(
            "tip_fillet_a",
            k,
            placed(&half.tip_fillet, before, true),
        ));
        segments.push(named(
            "tip",
            k,
            SegmentGeometry::Arc {
                center: [0.0, 0.0],
                radius: outside_radius,
                start_angle: before - half.tip_angle,
                end_angle: after + half.tip_angle,
            },
        ));
        segments.push(named(
            "tip_fillet_b",
            k,
            placed(&half.tip_fillet, after, false),
        ));
        if let Some(flank) = &half.flank {
            segments.push(named("flank_b", k, placed(flank, after, false)));
        }
        if let Some(fillet) = &half.bottom_fillet {
            segments.push(named("root_fillet_b", k, placed(fillet, after, false)));
        }
        segments.push(named("root", k, placed(&half.bottom, after, false)));
    }
    Ok(segments)
}

#[cfg(test)]
mod tests {
    use mitcad_vec3::vec2::distance;

    use super::super::gear_profile::{ends, loop_area, sample};
    use super::*;

    /// The loop's segments join end to end, in their order.
    fn assert_closed(segments: &[NamedSegment]) {
        let n = segments.len();
        for i in 0..n {
            let a = ends(&segments[i].geometry);
            let b = ends(&segments[(i + 1) % n].geometry);
            let gap = [a[0], a[1]]
                .iter()
                .flat_map(|p| [b[0], b[1]].map(|q| distance(*p, q)))
                .fold(f64::INFINITY, f64::min);
            assert!(
                gap < 1.0e-9,
                "{} and {} are {gap} apart",
                segments[i].name,
                segments[(i + 1) % n].name
            );
        }
    }

    /// The largest and smallest distances of the outline from the centre.
    fn radii(segments: &[NamedSegment]) -> (f64, f64) {
        let mut range = (f64::INFINITY, 0.0f64);
        for s in segments {
            for p in sample(&s.geometry, 64) {
                let r = p[0].hypot(p[1]);
                range = (range.0.min(r), range.1.max(r));
            }
        }
        range
    }

    #[test]
    fn outside_diameters_follow_the_pitch_line_offsets() {
        // N p / pi - 2 PLD, written out from the published values.
        let cases = [
            (BeltProfile::Gt2Pitch2, 20.0, 40.0 / PI - 0.508),
            (BeltProfile::Gt2Pitch3, 24.0, 72.0 / PI - 0.762),
            (BeltProfile::Htd3m, 30.0, 90.0 / PI - 0.762),
            (BeltProfile::Htd5m, 30.0, 150.0 / PI - 1.143),
            (BeltProfile::T5, 20.0, 100.0 / PI - 0.85),
            (BeltProfile::Xl, 15.0, 76.2 / PI - 0.508),
        ];
        for (profile, teeth, expected) in cases {
            let od = outside_diameter(profile, teeth, 0.0);
            assert!((od - expected).abs() < 1.0e-6, "{profile:?}: {od}");
            assert!(
                (pitch_diameter(profile, teeth) - teeth * profile.data().pitch / PI).abs()
                    < 1.0e-12
            );
            // The outline's tips lie on the outside circle, its groove
            // bottoms the groove's depth below.
            let outline = toothed_outline(profile, teeth, od / 2.0, 0.0).unwrap();
            let (inner, outer) = radii(&outline);
            assert!(
                (2.0 * outer - expected).abs() < 1.0e-6,
                "{profile:?}: {outer}"
            );
            let depth = profile.data().groove.depth;
            assert!(
                (inner - (od / 2.0 - depth)).abs() < 1.0e-6,
                "{profile:?}: {inner}"
            );
        }
    }

    #[test]
    fn outlines_close_with_one_tip_a_tooth() {
        for profile in PROFILES {
            let min = profile.data().min_teeth;
            for teeth in [min, 20.0, 37.0, 60.0] {
                let od = outside_diameter(profile, teeth, 0.0);
                let outline = toothed_outline(profile, teeth, od / 2.0, 0.3).unwrap();
                assert_closed(&outline);
                let tips = outline
                    .iter()
                    .filter(|s| s.name.starts_with("tip("))
                    .count();
                assert_eq!(tips, teeth as usize, "{profile:?}");
                let roots = outline
                    .iter()
                    .filter(|s| s.name.starts_with("root("))
                    .count();
                assert_eq!(roots, teeth as usize, "{profile:?}");
                // Less than the outside circle, more than the root circle.
                let area = loop_area(&outline);
                let ro = od / 2.0;
                let rr = ro - profile.data().groove.depth;
                assert!(area < PI * ro * ro && area > PI * rr * rr, "{profile:?}");
            }
        }
    }

    #[test]
    fn grooves_have_their_shapes() {
        // Straight-sided: a flat bottom with fillets; round: one arc.
        let xl = half_groove(BeltProfile::Xl, 20.0).unwrap();
        assert!(xl.bottom_fillet.is_some() && xl.flank.is_some());
        let gt2 = half_groove(BeltProfile::Gt2Pitch2, 6.0).unwrap();
        assert!(gt2.bottom_fillet.is_none() && gt2.flank.is_some());
        // The XL groove's flanks at 25 degrees to its axis.
        let g = BeltProfile::Xl.data().groove;
        assert!((g.flank_angle - 25f64.to_radians()).abs() < 1.0e-12);
        // The round grooves' flanks pass through the sharp corners: at the
        // corner's height the straight construction is half the width off
        // the axis.
        for profile in [
            BeltProfile::Gt2Pitch2,
            BeltProfile::Gt2Pitch3,
            BeltProfile::Htd3m,
            BeltProfile::Htd5m,
        ] {
            let g = profile.data().groove;
            let r = g.bottom_radius;
            let phi = g.flank_angle;
            // The tangent point (u, v) and the flank on to u = depth.
            let (u, v) = (r - r * phi.sin(), r * phi.cos());
            let at_top = v + (g.depth - u) * phi.tan();
            let width = match profile {
                BeltProfile::Gt2Pitch2 => 1.494,
                BeltProfile::Gt2Pitch3 => 2.31,
                BeltProfile::Htd3m => 2.27,
                _ => 3.781,
            };
            assert!((2.0 * at_top - width).abs() < 1.0e-9, "{profile:?}");
        }
    }

    #[test]
    fn too_few_teeth_are_refused() {
        let od = outside_diameter(BeltProfile::Htd5m, 4.0, 0.0);
        assert!(toothed_outline(BeltProfile::Htd5m, 4.0, od / 2.0, 0.0).is_err());
    }
}
